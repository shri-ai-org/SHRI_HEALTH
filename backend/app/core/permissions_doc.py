"""SECURITY_MODEL §4.3's role matrix, generated from core's permissions.py (a proposal).

Today the matrix is written twice, in SECURITY_MODEL §4.3 and in permissions.py, and a test
checks that they agree. So a permission change needs two commits on one branch, one per owner.
This makes permissions.py the single source: the table below is generated from it, and CI
checks the copy in SECURITY_MODEL, as #127 does for operations.json. Vimal still reviews every
permission change, as the permissions.py diff and the regenerated table land in the same PR.

    python -m app.core.permissions_doc                 # print the table
    python -m app.core.permissions_doc --check PATH    # exit 1 if PATH's copy is stale
    python -m app.core.permissions_doc --write PATH    # replace PATH's copy

The table goes between two markers, so the prose around it stays hand-written:

    <!-- permissions-table:start (generated by backend/app/core/permissions_doc.py) -->
    <!-- permissions-table:end -->

Rows: one per resource and set of roles, so every cell is ✓ or –, and contracts/scripts/
role_matrix.py reads it back to exactly ROLE_PERMISSIONS (tested). ‡ marks the rows the clinical
advisors still have to approve (Q21), from CLINICAL_REVIEW below.
"""

import argparse
import sys
from collections import defaultdict
from pathlib import Path

from app.core.permissions import CATALOGUE, ROLE_PERMISSIONS

# The column order of SECURITY_MODEL §4.3 (role_matrix.ROLES).
COLUMNS = ("FD", "MA", "RN", "MD", "APP", "BIL", "ADM", "CO", "SUP", "DSP")
START = "<!-- permissions-table:start (generated by backend/app/core/permissions_doc.py) -->"
END = "<!-- permissions-table:end -->"
# Resources whose rows wait for the clinical advisors (‡, DECISIONS Q21), as §4.3 marks them
# today. A permission's ‡ changes here, in the same reviewed PR as the permission itself.
CLINICAL_REVIEW = frozenset({
    "after-visit-summaries", "ai-suggestions", "alerts", "allergies", "appointments",
    "chart-summaries", "diagnoses", "medication-reconciliations", "medications",
    "refill-requests",
    "encounter-audio", "encounters", "family-history", "favorites", "in-office-results",
    "note-addenda", "note-drafts", "note-templates", "notes", "orders", "prescriptions",
    "problems", "results", "social-history", "surgical-history", "timeline", "transcriptions",
    "unmatched-results", "vitals",
})


def rows() -> list[tuple[str, tuple[bool, ...]]]:
    """(first cell, one flag per column), one row per resource and identical set of roles,
    sorted by resource and then by action, so the output only changes when a grant does."""
    unknown = set(ROLE_PERMISSIONS) - set(COLUMNS)
    if unknown:
        raise ValueError(f"roles with no column in §4.3: {sorted(unknown)}")
    groups: dict[tuple[str, tuple[bool, ...]], list[str]] = defaultdict(list)
    for permission in sorted(CATALOGUE):
        resource, action = permission.split(":", 1)
        flags = tuple(permission in ROLE_PERMISSIONS.get(role, frozenset()) for role in COLUMNS)
        groups[(resource, flags)].append(action)
    result = []
    for (resource, flags), actions in sorted(groups.items(),
                                             key=lambda item: (item[0][0], sorted(item[1]))):
        mark = "‡ " if resource in CLINICAL_REVIEW else ""
        name = f"`{resource}:{'\\|'.join(sorted(actions))}`"
        result.append((f"{mark}{name}", flags))
    return result


def table() -> str:
    lines = ["| Permission group | " + " | ".join(COLUMNS) + " |",
             "|---|" + "---|" * len(COLUMNS)]
    for first, flags in rows():
        lines.append(f"| {first} | " + " | ".join("✓" if f else "–" for f in flags) + " |")
    return "\n".join(lines) + "\n"


def section() -> str:
    return f"{START}\n{table()}{END}"


def _current(text: str) -> str | None:
    if START not in text or END not in text:
        return None
    return text[text.index(START):text.index(END) + len(END)]


def check(path: Path) -> list[str]:
    """Problems with PATH's copy of the table; empty when it matches permissions.py."""
    current = _current(path.read_text(encoding="utf-8"))
    if current is None:
        return [f"{path}: no generated permissions table (markers {START!r} … {END!r})"]
    if current != section():
        return [f"{path}: the permissions table is stale; run "
                "`python -m app.core.permissions_doc --write` and commit the result"]
    return []


def write(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    current = _current(text)
    if current is None:
        raise SystemExit(f"{path}: add the markers first ({START} … {END})")
    path.write_text(text.replace(current, section()), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", type=Path, metavar="PATH")
    group.add_argument("--write", type=Path, metavar="PATH")
    args = parser.parse_args(argv)
    if args.check:
        problems = check(args.check)
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    if args.write:
        write(args.write)
        return 0
    sys.stdout.write(table())
    return 0


if __name__ == "__main__":
    sys.exit(main())
